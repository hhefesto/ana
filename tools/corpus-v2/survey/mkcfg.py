# run 6's collection config from run 5's: every run-5 `repo` and `growth` line becomes a growth
# line (same rule and excludes), the survey's new repositories become `repo ... all` lines.
#   mkcfg.py RUN5CFG NEWREPOS(OWNER/NAME TAB comment a line) OUT
import sys
src, newf, out = sys.argv[1:4]
lines = open(src).read().split('\n')
new = [l.split('\t') for l in open(newf).read().split('\n') if l.strip() and not l.startswith('#')]
head = '''# Run 6's new Bend code (2026-10-28):
#
#   bend-corpus-v2 collect tools/corpus-v2/collect/bend-run6.cfg all
#
# from the repository root.  Run 5's config with:
#   - BendHub again (`hub`): its listing had 991 package versions on 10-28 (634 on 10-16), 475
#     names; a name run 5 took is a repository the corpus holds (only its new paths are new, and
#     it is never a vault candidate), the 104 new names are new repositories;
#   - growth of every repository run 5 took (its 40 `repo` and 97 `growth` lines, at their rules);
#   - the Bend 2 repositories the 2026-10-28 GitHub survey found that no collection holds
#     (code search `extension:bend`, bisected by size: 41,113 files in 385 repositories; each
#     unknown repository's first, middle and last .bend file sampled and marked Bend 2 by
#     `import Base`/`.bend` imports, `0n` literals, typed arrows, `is`, proofs, `&2`), as
#     `repo ... all` (87 repositories);
#   - the survey's Bend 2 repositories whose ids the corpus holds (runs 1-2's raw-new and raw)
#     but no PINS file names, never grown since: `growth ... all` (75; aricarmo/godot-bend
#     without godot/api/, generated by its tools/gen_api.py);
#   - the upstream's .bend files added or changed since run 5's pin (234cb9b9);
#   - the loader is the flake's Bend 2.0.39 (BEND_NO_TELEMETRY=1), the corpus run 5's outputs,
#     its port and pool 5b besides runs 2-4's; vault-known and big-known add run 5's.
# Left out as in run 5 (Bend 1 repositories, compiler output, copies, submodule-only trees), and
# the survey's 61 Bend 1 repositories and 45 with no Bend marker (OpenFOAM, LaTeX, HVM, ...);
# github-linguist/linguist and amrierscuo/github-linguist-hello-world-corpus (samples copied from
# other repositories).
'''
body = []
skip = False
for l in lines:
    w = l.split()
    if l.startswith('#') and not body:
        continue  # run 5's header
    if not w:
        body.append(l); continue
    k = w[0]
    if k == 'out': l = 'out run/v6/collect/bend'
    elif k == 'src': l = 'src run/v6/collect/src/bend'
    elif k == 'pins': l = 'pins run/v6/collect/src/PINS.tsv'
    elif k == 'known': l = 'known run/v2/raw-new3/src/PINS.tsv run/v4/collect/src/PINS.tsv run/v5/collect/src/PINS.tsv'
    elif k == 'upstream': l = 'upstream bendlang/bend 234cb9b950800f20b15feafcb4ce2f43e76e7fae'
    elif k == 'loader': l = 'loader /home/hhefesto/src/ana/run/v5/gcroot-bend-2.0.39/bin/bend'
    elif k == 'vault-known': l = l + ' run/v5/collect/bend/vault/repos.txt'
    elif k == 'big-known': l = l + ' run/v5/collect/bend/stage/pre/big.repos'
    elif k == 'keycache': l = 'keycache run/v6/collect/keycache'
    elif k == 'repo': l = 'growth' + l[4:]
    body.append(l)
# the corpus: run 5's outputs, its port and pool 5b, after run 5's corpus lines
idx = max(i for i, l in enumerate(body) if l.startswith('corpus '))
body.insert(idx + 1, 'corpus run/v5/collect/bend/bend.jsonl run/v5/collect/bend/vault/bend.jsonl run/v5/collect/bend/holdout/bend.jsonl')
body.insert(idx + 2, 'corpus run/v5/port/bend.jsonl run/v5/ratio/raw/bend-run5b.jsonl')
# NEWREPOS rows: OWNER/NAME TAB comment [TAB repo|growth [TAB excluded prefixes, space-separated]]
for kind, title in (('repo', 'the 2026-10-28 survey\'s new Bend 2 repositories'),
                    ('growth', 'the survey\'s Bend 2 repositories an earlier collection took without a pin\n'
                               '# (their ids are in the corpus; never grown since): only paths the corpus never had')):
    rows = [r for r in new if (r[2] if len(r) > 2 and r[2] else 'repo') == kind]
    if not rows: continue
    body.append('')
    body.append('# ' + title + ' (a comment line: what the survey saw)')
    for r in rows:
        if len(r) > 1 and r[1]: body.append('# ' + r[1])
        ex = r[3].split() if len(r) > 3 else []
        body.append('%s %s all%s' % (kind, r[0], (' exclude ' + ' '.join(ex)) if ex else ''))
open(out, 'w').write(head + '\n'.join(body).rstrip('\n') + '\n')
print('growth', sum(1 for l in body if l.startswith('growth ')), 'repo', sum(1 for l in body if l.startswith('repo ')))
print('sibling', sum(1 for l in body if l.startswith('sibling ')), 'hub', sum(1 for l in body if l.startswith('hub ')))
